# ==============================
# 🔹 IMAGE PROCESSING
# ==============================
def preprocess_image(image_bytes, target_size=(224, 224)):
    image = Image.open(BytesIO(image_bytes)).convert("RGB")
    image = image.resize(target_size)
    image = np.array(image, dtype=np.float32) / 255.0
    return image

def encode_image(image_bytes):
    return base64.b64encode(image_bytes).decode('utf-8')

# ==============================
# 🔹 TEXT PROCESSING
# ==============================
def extract_info(text, keyword):
    # Allow variations like Treatment, Treatments, Management
    keywords_map = {
        "Disease Description": ["Disease Description"],
        "Cause": ["Cause", "Causes"],
        "Treatment": ["Treatment", "Treatments", "Management", "Prevention"]
    }

    for key in keywords_map.get(keyword, [keyword]):
        pattern = rf"{key}\s*[:\-]\s*(.*?)(?=\n[A-Za-z ]+\s*[:\-]|$)"
        match = re.search(pattern, text, re.DOTALL | re.IGNORECASE)

        if match:
            return match.group(1).strip()

    return "Info not available."

# ==============================
# 🔹 HUGGING FACE FUNCTION
# ==============================
def get_disease_info(disease_name):

    import re

    disease_name = disease_name.replace("__", " ").replace("_", " ")
    disease_name = re.sub(r'\s+', ' ', disease_name).strip()

    if disease_name in cache:
        print("✅ From cache:", disease_name)
        return cache[disease_name]
    
    # 🔹 Rate limit control (ADD HERE)
    global last_api_call
    if time.time() - last_api_call < 1:
        time.sleep(1)
    last_api_call = time.time()

    prompt = f"""
You are an expert plant pathologist.

Give COMPLETE and structured information about {disease_name}.

IMPORTANT:
You MUST include ALL 3 sections.

Format strictly like this:

Disease Description:
Write 2-3 lines.

Cause:
Write 2-3 points.

Treatment:
Write 3-4 points.

DO NOT skip any section.
"""

    try:
        response = client.chat_completion(
            messages=[
                {"role": "user", "content": prompt}
            ],
            max_tokens=1000,
            temperature=0.5
        )

        text = response.choices[0].message.content
        print("=== FULL AI RESPONSE ===")
        print(text)
        print("========================")

        disease_info = extract_info(text, "Disease Description")
        cause = extract_info(text, "Cause")
        treatment = extract_info(text, "Treatment")

        # Smart fallback for missing sections
        if "Info not available" in cause:
            cause = "This disease is mainly caused by viral, fungal, or bacterial infection affecting plant growth."

        if "Info not available" in treatment:
            treatment = """1. Remove infected leaves
            2. Use recommended pesticides
            3. Control insects like whiteflies
            4. Maintain proper field hygiene"""

    except Exception as e:
        print("❌ HF Error:", e)
        return fallback_data()

    cache[disease_name] = (disease_info, cause, treatment)

    return disease_info, cause, treatment

# ==============================
# 🔹 FALLBACK
# ==============================
def fallback_data():
    return (
        "This disease affects plant health and reduces crop productivity.",
        "Caused by fungal, bacterial, or environmental factors.",
        "Use proper pesticides, remove infected leaves, and maintain hygiene."
    )

# ==============================
# 🔹 PREDICTION
# ==============================
def predict_single_image(image_bytes):
    image = preprocess_image(image_bytes)

    image_expanded = np.expand_dims(image, axis=0).astype(np.float32)
    interpreter.set_tensor(input_details[0]['index'], image_expanded)

    start_time = time.time()
    interpreter.invoke()
    end_time = time.time()

    output_data = interpreter.get_tensor(output_details[0]['index'])
    predicted_index = np.argmax(output_data)
    predicted_class = class_names[predicted_index]
    confidence_score = output_data[0][predicted_index] * 100
    prediction_time = end_time - start_time

    print("Predicted:", predicted_class)
    clean_name = predicted_class.replace("_", " ")

    disease_info, cause, treatment = get_disease_info(clean_name)
    return predicted_class, confidence_score, prediction_time, disease_info, cause, treatment

