# ==============================
app.config["MAX_CONTENT_LENGTH"] = 12 * 1024 * 1024

@app.route("/", methods=["GET", "POST"])
def upload_file():
    if request.method == "POST":
        files = request.files.getlist("files")

        if not files or all(file.filename == "" for file in files):
            return render_template("upload.html", error="No files selected!")

        new_results = []

        for file in files:
            image_bytes = file.read()
            encoded_image = encode_image(image_bytes)

            predicted_class, confidence, time_taken, disease_info, cause, treatment = predict_single_image(image_bytes)

            global latest_result

            latest_result = {
                "disease": predicted_class,
                "confidence": f"{confidence:.2f}%",
                "treatment": treatment,
                "image": encoded_image
            }

            new_results.append({
                "image": encoded_image,
                "disease": predicted_class,
                "confidence": f"{confidence:.2f}%",
                "time_taken": f"{time_taken:.4f} sec",
                "disease_info": disease_info,
                "cause": cause,
                "treatment": treatment
            })

        return render_template("result.html", results=new_results)

    return render_template("upload.html")

