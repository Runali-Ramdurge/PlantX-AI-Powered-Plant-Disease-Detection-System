@app.route('/download_report')
def download_report():
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Image
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.lib.units import inch

    REPORT_FOLDER = os.path.join('static', 'reports')
    os.makedirs(REPORT_FOLDER, exist_ok=True)

    file_path = os.path.join(REPORT_FOLDER, 'report.pdf')

    #  Save image temporarily
    image_path = os.path.join(REPORT_FOLDER, 'plant.jpg')

    # Decode base64 image (latest uploaded image)
    if latest_result.get("image"):
        with open(image_path, "wb") as f:
            f.write(base64.b64decode(latest_result["image"]))

    # Create PDF
    doc = SimpleDocTemplate(file_path)
    styles = getSampleStyleSheet()

    content = []

    # 🔹 Title
    content.append(Paragraph("🌿 Plant Disease Detection Report", styles['Title']))
    content.append(Spacer(1, 20))

    # 🔹 Image
    if os.path.exists(image_path):
        img = Image(image_path, width=4*inch, height=3*inch)
        content.append(img)
        content.append(Spacer(1, 20))

    # 🔹 Details
    content.append(Paragraph("<b>Disease:</b> " + latest_result.get("disease", "N/A"), styles['Normal']))
    content.append(Spacer(1, 10))

    content.append(Paragraph("<b>Confidence:</b> " + latest_result.get("confidence", "N/A"), styles['Normal']))
    content.append(Spacer(1, 15))

    content.append(Paragraph("<b>Treatment:</b>", styles['Heading2']))
    content.append(Spacer(1, 10))

    content.append(Paragraph(latest_result.get("treatment", "N/A"), styles['Normal']))

    content.append(Spacer(1, 20))

    content.append(Paragraph("✔ Generated by Plant Disease Detection System", styles['Italic']))

    # Build PDF
    doc.build(content)

    return send_file(file_path, as_attachment=True)

